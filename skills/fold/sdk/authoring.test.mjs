import assert from 'node:assert/strict';
import {FoldPlan,datum} from './authoring.mjs';
const plan=new FoldPlan({revision:0,project_epoch:0});
const doc=plan.document('title');
const text=doc.object('label','fold.motion.text','Title').set('text','i love katie');
doc.node('driver','fold.motion.oscillator').set('frequency',0.125);
text.set('size',48);
const batch=plan.batch('create','Build title');
assert.equal(batch.operations.length,3);
assert.equal(batch.operations[1].edits.length,5);
assert.throws(()=>doc.node('label','fold.motion.math'),/Conflicting/);
assert.throws(()=>datum(NaN));
const handles={'title':'document-uuid','title/label':'text-uuid'};
const update=new FoldPlan({revision:1,project_epoch:0,handles});
update.document('title').object('label','fold.motion.text').set('text','artist continuation');
const changed=update.batch('update','Update title');
assert.deepEqual(changed.ids,[]);
assert.deepEqual(changed.operations.slice(0,1),[{op:'edit',document:'document-uuid',edits:[{op:'set',node:'text-uuid',input:'text',value:{Text:'artist continuation'}}]}]);
batch.operations.length=0;
assert.equal(plan.batch('another','Copy').operations.length,3);
console.log('Authoring SDK identity, preservation and literal checks passed');
const saved={motion:{id:'doc',signature:'document:fold.motion.document'},'motion/label':{id:'text',signature:'object:fold.motion.text'}};
const repeat=new FoldPlan({revision:2,project_epoch:5,namespace:'demo',bindings:saved});
repeat.document('motion').text('label','must not overwrite',{size:999});
assert.equal(repeat.batch('repeat','Repeat').operations.filter(o=>o.op==='edit').length,0);
assert.throws(()=>repeat.document('motion').node('label','fold.motion.math'),/Conflicting/);
const explicit=new FoldPlan({revision:2,project_epoch:5,bindings:saved});
explicit.document('motion').text('label','ignored').set('size',42);
assert.deepEqual(explicit.batch('edit','Edit').operations[0].edits,[{op:'set',node:'text',input:'size',value:{Scalar:42}}]);
